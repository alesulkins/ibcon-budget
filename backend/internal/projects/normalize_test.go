package projects

import "testing"

// TestNormalizeFullName — приведение ФИО к формату «Фамилия И.О.».
func TestNormalizeFullName(t *testing.T) {
	tests := []struct {
		in, want string
	}{
		// Инициалы уже есть, нужен только регистр
		{"иванов и.о.", "Иванов И.О."},
		{"Иванов и.о.", "Иванов И.О."},
		{"ИВАНОВ И.О.", "ИВАНОВ И.О."}, // фамилию не ломаем, если уже капсом
		// Пробелы между инициалами
		{"иванов и. о.", "Иванов И.О."},
		{"фамилия и. о. ", "Фамилия И.О."},
		// Полное имя-отчество сворачивается в инициалы
		{"иванов иван олегович", "Иванов И.О."},
		{"петров пётр", "Петров П."},
		// Одна фамилия
		{"иванов", "Иванов"},
		{"  иванов  ", "Иванов"},
		// Латиница тоже работает
		{"smith j.r.", "Smith J.R."},
		// Пустые значения не должны падать
		{"", ""},
		{"   ", ""},
		{".", "."},
	}

	for _, tt := range tests {
		if got := normalizeFullName(tt.in); got != tt.want {
			t.Errorf("normalizeFullName(%q) = %q, want %q", tt.in, got, tt.want)
		}
	}
}

// TestCapitalizeFirst — первая буква заглавная, остальное не трогаем.
func TestCapitalizeFirst(t *testing.T) {
	tests := []struct {
		in, want string
	}{
		{"ромашка", "Ромашка"},
		{"Ромашка", "Ромашка"},
		// Организационно-правовые формы всегда заглавными, а с заглавной
		// поднимается следующее за ними значащее слово.
		{"ооо ромашка", "ООО Ромашка"},
		{"ооо «тест»", "ООО «тест»"},
		{"зао василёк", "ЗАО Василёк"},
		{"ип петров", "ИП Петров"},
		{"ао", "АО"},
		{"пао сбербанк", "ПАО Сбербанк"},
		{"ООО Ромашка", "ООО Ромашка"},         // уже правильно — не ломаем
		{"строймонтаж ооо", "Строймонтаж ООО"}, // форма в конце тоже поднимается
		{"  омск", "Омск"},
		{"", ""},
		{"123 объект", "123 объект"}, // цифра не капитализируется
	}
	for _, tt := range tests {
		if got := capitalizeFirst(tt.in); got != tt.want {
			t.Errorf("capitalizeFirst(%q) = %q, want %q", tt.in, got, tt.want)
		}
	}
}

// TestLegalFormsDoNotLeakIntoNames — правило про ООО/АО/ИП относится к
// названиям организаций, но НЕ к ФИО: фамилия «Ип» не должна
// превращаться в «ИП».
func TestLegalFormsDoNotLeakIntoNames(t *testing.T) {
	if got := normalizeFullName("ип сидоров"); got != "Ип С." {
		t.Errorf("normalizeFullName(\"ип сидоров\") = %q, want %q", got, "Ип С.")
	}
	if got := normalizeFullName("ао петров"); got != "Ао П." {
		t.Errorf("normalizeFullName(\"ао петров\") = %q, want %q", got, "Ао П.")
	}
	// А в названии организации — по-прежнему заглавными
	if got := capitalizeFirst("ип сидоров"); got != "ИП Сидоров" {
		t.Errorf("capitalizeFirst(\"ип сидоров\") = %q, want %q", got, "ИП Сидоров")
	}
}
