package calc

import "fmt"

// ── Лист 4.10 «ГПХ сотрудников» ─────────────────────────────────────────────
//
// Самый простой лист контура: экономист задаёт ДВА числа на весь проект —
// среднее количество исполнителей в месяц и среднюю стоимость одного, — а
// расход всех месяцев получается одинаковым:
//
//	итог_месяца = среднее количество × средняя стоимость
//
// Уходит одной строкой в 2.Бюджет: строка 201 «Субподрядные работы
// (ГПХ сотрудников)».
//
// В таблицу по месяцам экономист не вводит ничего — она только показывает
// результат (владелец 2026-08-26). Поэтому и структура ввода не массив по
// месяцам, а два скаляра: помесячный ввод здесь просто нечему хранить.
//
// Расчётных формул в листе нет, сверка с Excel по нему не проводилась.
//
// ОТЛОЖЕНО: индексация ГПХ. По ФОТ есть ежегодная апрельская индексация
// (санкционированное отклонение №1, fot.go), для ГПХ решения пока нет —
// см. docs/open_questions.md. Сейчас стоимость одинакова во всех месяцах.

// InputGphEmployees — данные листа 4.10.
type InputGphEmployees struct {
	// AvgCount — среднее количество исполнителей по ГПХ в месяц.
	// Дробное значение допустимо: это среднее, а не штучный счёт.
	AvgCount float64 `json:"avg_count"`
	// AvgCost — средняя стоимость одного исполнителя за месяц.
	AvgCost float64 `json:"avg_cost"`
}

// calcGphEmployees рассчитывает лист 4.10. Возвращает массив длиной duration:
// во всех месяцах одна и та же сумма → 2.Бюджет строка 201.
func calcGphEmployees(in *InputGphEmployees, duration int) []float64 {
	out := make([]float64, duration)
	if in == nil || duration <= 0 {
		return out
	}
	perMonth := in.AvgCount * in.AvgCost
	for m := 0; m < duration; m++ {
		out[m] = perMonth
	}
	return out
}

// ValidateGphEmployees проверяет ввод листа 4.10: оба числа неотрицательны.
// Ноль допустим — ГПХ на проекте может не быть вовсе.
func ValidateGphEmployees(in *InputGphEmployees) error {
	if in == nil {
		return nil
	}
	if in.AvgCount < 0 {
		return fmt.Errorf("ГПХ сотрудников: среднее количество не может быть отрицательным (%.2f)",
			in.AvgCount)
	}
	if in.AvgCost < 0 {
		return fmt.Errorf("ГПХ сотрудников: средняя стоимость не может быть отрицательной (%.2f)",
			in.AvgCost)
	}
	return nil
}
