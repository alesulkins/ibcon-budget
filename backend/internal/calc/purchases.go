package calc

import "fmt"

// ── Листы-покупки: 4.7 «Приборы стройконтроля», 4.12 «Корпоративы» ──────────
//
// Оба листа устроены одинаково: таблица строк, у каждой месяц, количество и
// цена за единицу. Расход месяца — сумма `цена × количество` по строкам, чей
// месяц равен этому. Итог уходит ОДНОЙ строкой в 2.Бюджет:
//
//	4.7  Приборы строительного контроля → строка 189
//	4.12 Корпоративные мероприятия      → строка 205
//
// Расчёт тот же, что у покупки авто (4.3) и вагончиков (4.4), но БЕЗ
// ограничения на хвост проекта: приборы и корпоративы допустимы в любом
// месяце, включая последние два. Ограничение из 4.4 (purchaseAllowedMonths)
// здесь сознательно НЕ применяется — оно правило конкретно вагончиков,
// подтверждено владельцем 2026-08-26.
//
// Расчётных формул в этих листах нет, поэтому сверка с Excel по ним не
// проводилась (то же решение владельца).

// InputPurchases — ввод листа-покупок (4.7, 4.12).
//
// Строка — ItemPurchase, тот же тип, что у покупки авто и вагончиков:
// набор полей совпадает. У 4.12 поле Name не используется — у корпоратива
// в форме только месяц, количество участников и цена за человека, — но
// остаётся в структуре, чтобы название можно было добавить без миграции
// сохранённых данных.
type InputPurchases struct {
	Items []ItemPurchase `json:"items"`
}

// calcPurchases рассчитывает лист-покупок. Возвращает массив длиной duration:
// расход месяца = Σ (цена × количество) по строкам, чей месяц равен этому.
func calcPurchases(in *InputPurchases, duration int) []float64 {
	out := make([]float64, duration)
	if in == nil || duration <= 0 {
		return out
	}
	for i := range in.Items {
		p := &in.Items[i]
		// Месяц не заполнен (0) — строка таблицы пустая, игнорируется целиком.
		// Месяц за пределами проекта отклоняет ValidatePurchases; проверка
		// здесь — страховка на случай данных, сохранённых до сокращения
		// длительности проекта.
		if p.Month < 1 || p.Month > duration {
			continue
		}
		out[p.Month-1] += p.Price * float64(p.Count)
	}
	return out
}

// purchasesTitle — название листа для текста ошибки валидации. Экономист
// видит его в тосте, поэтому это подпись шага мастера, а не ключ ввода.
func purchasesTitle(inputType string) string {
	if inputType == TypeCorporateEventsItems {
		return "корпоративные мероприятия"
	}
	return "приборы строительного контроля"
}

// ValidatePurchases проверяет ввод листа-покупок: месяц обязан лежать внутри
// проекта, цена и количество — быть неотрицательными.
//
// Пустой месяц (0) означает незаполненную строку таблицы и пропускается, как
// в 4.3 и 4.4. В отличие от вагончиков, последние два месяца проекта здесь
// разрешены наравне с остальными.
func ValidatePurchases(title string, in *InputPurchases, duration int) error {
	if in == nil {
		return nil
	}
	for i := range in.Items {
		p := &in.Items[i]
		if p.Price < 0 {
			return fmt.Errorf("%s, строка %d: цена не может быть отрицательной (%.2f)",
				title, i+1, p.Price)
		}
		if p.Count < 0 {
			return fmt.Errorf("%s, строка %d: количество не может быть отрицательным (%d)",
				title, i+1, p.Count)
		}
		if p.Month == 0 {
			continue // строка не заполнена — игнорируется целиком
		}
		if p.Month < 1 || p.Month > duration {
			return fmt.Errorf(
				"%s, строка %d: месяц %d вне проекта, допустимо от 1 до %d",
				title, i+1, p.Month, duration)
		}
	}
	return nil
}
