-- Справочные значения справочников: оклад у должности и процентные
-- ставки у исполнителя.
--
-- Общий смысл: справочник задаёт значение ПО УМОЛЧАНИЮ для ячейки
-- мастера проекта, а не жёсткую константу расчёта. В сохранённом
-- бюджете лежит уже подставленное число (snapshot), поэтому правка
-- справочника не меняет ни одной посчитанной версии.

-- ── Должности: оклад ────────────────────────────────────────────────────
-- Переносится в шаг «Сотрудники» мастера как значение по умолчанию,
-- экономист правит его вручную без подтверждения. Пока у всех 0 —
-- реальные оклады заполняет главный экономист.
ALTER TABLE positions ADD COLUMN IF NOT EXISTS salary NUMERIC(18,2) NOT NULL DEFAULT 0;

-- ── Исполнители: процентные ставки ──────────────────────────────────────
-- Хранятся в процентах (25 = 25%), как их вводит главный экономист и как
-- они показаны в форме.
ALTER TABLE executors ADD COLUMN IF NOT EXISTS profit_tax_rate   NUMERIC(6,3) NOT NULL DEFAULT 25;
ALTER TABLE executors ADD COLUMN IF NOT EXISTS refinancing_rate  NUMERIC(6,3) NOT NULL DEFAULT 14.5;

-- Актуальные значения по трём исполнителям. У «Айбикон-Проект» налога на
-- прибыль нет; у киргизского филиала ставка 4% — новое актуальное
-- значение вместо прежней формы «5% + 2%» (2.Бюджет!G240),
-- см. docs/deviations.md, отклонение №4.
UPDATE executors SET profit_tax_rate = 25  WHERE name = 'Айбикон';
UPDATE executors SET profit_tax_rate = 0   WHERE name = 'Айбикон-Проект';
UPDATE executors SET profit_tax_rate = 4   WHERE name = 'Айбикон Киргизия';
UPDATE executors SET refinancing_rate = 14.5;

