-- Признак ИТР (инженерно-технический работник) у должности.
--
-- Нужен для сводки по ИТР в выгрузке бюджета: там считают, сколько
-- инженеров в среднем работало в месяц и во сколько обходится
-- человеко-месяц. Рабочие и административный персонал в эту статистику
-- не входят, поэтому признак задаётся у должности, а не выводится из
-- названия.
ALTER TABLE positions ADD COLUMN IF NOT EXISTS is_itr BOOLEAN NOT NULL DEFAULT FALSE;
